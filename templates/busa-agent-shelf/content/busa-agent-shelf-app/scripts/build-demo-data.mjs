// Builds app/js/providers/demo-data.js from the template's canonical sample
// rows (content/<base>/records.ndjson), so ?demo=1 shows exactly the dataset
// an install merges — no second, drifting copy of the demo.
//
// Rows are shaped like the records API returns them: fields keyed by slug,
// a `rec…` record id, and relation values as the TARGET RECORD ID (not the
// package-local key and not a pre-resolved object), so demo mode exercises the
// same relation-resolution path live data does.
//
//   node scripts/build-demo-data.mjs          write the module
//   node scripts/build-demo-data.mjs --check  exit 1 when it is out of date
import { readFile, writeFile } from "node:fs/promises";
import path from "node:path";

const root = path.resolve(import.meta.dirname, "..");
const contentDir = path.resolve(root, "..");
const target = path.join(root, "app", "js", "providers", "demo-data.js");
const KEYS = ["questions", "observations", "competitors", "fixes", "settings"];
const RELATIONS = { observations: ["question"], fixes: ["question"] };

// Deterministic id from an FNV-1a hash. Deliberately `rec_demo_…`, not the
// 18-char `rec…` shape: a real-looking id in a published file is exactly what
// `busabase-cli check` rejects as a leaked workspace id. It is still a bare id
// string, so the app's relation-resolution path runs unchanged.
const mintId = (prefix, key) => {
  let hash = 0xcbf29ce484222325n;
  for (const char of key) {
    hash ^= BigInt(char.codePointAt(0));
    hash = (hash * 0x100000001b3n) & 0xffffffffffffffffn;
  }
  return `${prefix}_demo_${hash.toString(36).padStart(12, "0").slice(-12)}`;
};

const readRows = async (key) => {
  const text = await readFile(path.join(contentDir, key, "records.ndjson"), "utf8");
  return text
    .split("\n")
    .map((line) => line.trim())
    .filter(Boolean)
    .map((line) => JSON.parse(line));
};

const sources = Object.fromEntries(await Promise.all(KEYS.map(async (key) => [key, await readRows(key)])));
const idByKey = new Map();
for (const key of KEYS) for (const row of sources[key]) idByKey.set(row.key, mintId("rec", `${key}/${row.key}`));

const data = {};
for (const key of KEYS) {
  data[key] = sources[key].map((row) => {
    const fields = { ...row.fields };
    for (const slug of RELATIONS[key] || []) {
      if (fields[slug] == null || fields[slug] === "") continue;
      const id = idByKey.get(fields[slug]);
      if (!id) throw new Error(`${key}/${row.key}: relation ${slug} points at unknown key ${fields[slug]}`);
      fields[slug] = id;
    }
    return { ...fields, __recordId: idByKey.get(row.key), __headCommitId: mintId("cmt", `commit/${key}/${row.key}`) };
  });
}

const output = `// GENERATED by scripts/build-demo-data.mjs from content/*/records.ndjson — do not edit.
// Demo rows use the live API's shapes (bare record ids; relation = target record id).
export const demoRows = ${JSON.stringify(data, null, 2)};
`;

if (process.argv.includes("--check")) {
  const current = await readFile(target, "utf8").catch(() => "");
  if (current !== output) {
    console.error("app/js/providers/demo-data.js is out of date; run node scripts/build-demo-data.mjs");
    process.exit(1);
  }
  console.log("demo-data.js matches content/*/records.ndjson");
} else {
  await writeFile(target, output);
  console.log(`wrote ${path.relative(root, target)} (${KEYS.map((key) => `${key}:${data[key].length}`).join(", ")})`);
}
